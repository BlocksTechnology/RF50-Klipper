"""Write a test_klippy .test asserting the RF50 config defines every command BlocksScreen emits, minus the skip list."""

import fnmatch
import sys
from pathlib import Path

from bs_gcode_cmds import scan

# Sanity floor: BlocksScreen@dev sends ~24 literal commands; far fewer means the scan read the wrong tree.
MIN_SCANNED = 15


def load_entries(path: Path) -> dict[str, str]:
    """First token per line mapped to the rest (the reason); '#' starts a comment."""
    entries = {}
    for raw in path.read_text().splitlines():
        line = raw.split("#", 1)[0].strip()
        if line:
            name, _, reason = line.partition(" ")
            entries[name] = reason.strip()
    return entries


def resolve(found: dict[str, set[str]], skips: dict[str, str], extras: dict[str, str]) -> tuple[list[str], list[str], list[str]]:
    """Return (required, skipped, errors): skips drop names, extras add names and expand NAME_* sends."""
    expansions, plain = {}, []
    for entry in extras:
        pattern, sep, names = entry.partition("=")
        if sep:
            expansions[pattern] = [n for n in names.split(",") if n]
        else:
            plain.append(entry)
    required, skipped, errors = set(), [], []
    for name in sorted(found):
        if any(fnmatch.fnmatchcase(name, p) for p in skips):
            skipped.append(name)
        elif name.endswith("*"):
            if name in expansions:
                required.update(expansions[name])
            else:
                errors.append(f"{name} has a runtime suffix; list its real names in contract_extra.txt as {name}=A,B")
        else:
            required.add(name)
    for pattern in expansions:
        if pattern not in found:
            errors.append(f"contract_extra.txt expands {pattern}, which BlocksScreen no longer sends; remove it")
    required.update(plain)
    errors += [f"skip entry {p} matches nothing BlocksScreen sends; remove it" for p in skips if not any(fnmatch.fnmatchcase(n, p) for n in found)]
    errors += [f"{n} is both required (contract_extra.txt) and skipped" for n in plain if any(fnmatch.fnmatchcase(n, p) for p in skips)]
    return sorted(required), skipped, errors


def main(bs_root: str, skip_file: str, extra_file: str, out_test: str) -> int:
    """Scan bs_root, apply skips and extras, write one CI_ASSERT_COMMANDS test to out_test; 1 on any error."""
    root = Path(bs_root)
    if not root.is_dir() or not any(root.rglob("*.py")):
        sys.stderr.write(f"contract: ERROR no BlocksScreen sources under {root}\n")
        return 1
    res = scan(root)
    required, skipped, errors = resolve(res.found, load_entries(Path(skip_file)), load_entries(Path(extra_file)))
    errors += [f"cannot parse {e}" for e in res.errors]
    if len(res.found) < MIN_SCANNED:
        errors.append(f"only {len(res.found)} commands scanned (floor {MIN_SCANNED}); wrong BlocksScreen tree?")
    for name in required:
        sites = res.found.get(name)
        sys.stderr.write(f"contract: {name:28} {min(sites) if sites else 'contract_extra.txt'}\n")
    for site in res.dynamic:
        sys.stderr.write(f"contract: dynamic  {site}\n")
    sys.stderr.write(f"contract: {len(required)} required, {len(skipped)} skipped ({', '.join(skipped)})\n")
    if errors:
        for e in errors:
            sys.stderr.write(f"contract: ERROR {e}\n")
        return 1
    Path(out_test).write_text(
        "# Generated by tools/contract_test.py; do not edit.\n"
        "CONFIG ../../ci.cfg\n"
        "DICTIONARY mcu.dict Toolhead=Toolhead.dict pi=pi.dict beacon=beacon.dict\n"
        f"CI_ASSERT_COMMANDS CMDS={','.join(required)}\n"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main(*sys.argv[1:5]))
