"""Write a test_klippy .test asserting the RF50 config defines every command BlocksScreen emits, minus the skip list."""

import fnmatch
import sys
from pathlib import Path

from bs_gcode_cmds import scan


def load_skips(path: Path) -> dict[str, str]:
    """Skip patterns (NAME or PREFIX*) mapped to their reason; '#' starts a comment."""
    skips = {}
    for raw in path.read_text().splitlines():
        line = raw.split("#", 1)[0].strip()
        if line:
            name, _, reason = line.partition(" ")
            skips[name] = reason.strip()
    return skips


def main(bs_root: str, skip_file: str, out_test: str) -> None:
    """Scan bs_root, drop skipped names, write one CI_ASSERT_COMMANDS test to out_test."""
    found = scan(Path(bs_root))
    skips = load_skips(Path(skip_file))
    required, skipped = [], []
    for name, sites in sorted(found.items()):
        hit = next((p for p in skips if fnmatch.fnmatchcase(name, p)), None)
        (skipped if hit else required).append(name)
        if not hit:
            sys.stderr.write(f"contract: {name:28} {sorted(sites)[0]}\n")
    unused = [p for p in skips if not any(fnmatch.fnmatchcase(n, p) for n in found)]
    for p in unused:
        sys.stderr.write(f"contract: WARNING skip entry {p} matches nothing BlocksScreen sends, remove it\n")
    Path(out_test).write_text(
        "# Generated by tools/contract_test.py; do not edit.\n"
        "CONFIG ../../ci.cfg\n"
        "DICTIONARY mcu.dict Toolhead=Toolhead.dict pi=pi.dict beacon=beacon.dict\n"
        f"CI_ASSERT_COMMANDS CMDS={','.join(required)}\n"
    )
    sys.stderr.write(f"contract: {len(required)} required, {len(skipped)} skipped ({', '.join(skipped)})\n")


if __name__ == "__main__":
    main(*sys.argv[1:4])
